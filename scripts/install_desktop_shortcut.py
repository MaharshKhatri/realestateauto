"""One-click launchers for the dashboard: double-click → the cockpit starts (if it isn't already running) and opens
in the browser at http://127.0.0.1:8000.

    python manage.py install-shortcut          # or: python scripts/install_desktop_shortcut.py

Writes three launchers into the repository root (path-independent, safe to commit):
    Launch_Dashboard.command   macOS (double-click in Finder)
    launch_dashboard.sh        Linux
    Launch_Dashboard.bat       Windows
and copies the one for this computer to ~/Desktop as "Launch NJ Wholesale Dashboard" with the repository path
written in (plus a .desktop entry on Linux desktops), so it works from anywhere.

Each launcher: cd into the repository → pick the project's virtualenv Python if there is one (.venv / venv) →
check GET /api/health → if the cockpit isn't answering, start `python manage.py server` in the background with
output in logs/server.log → wait until /api/health answers (usually 1-2 seconds) → open the browser.
Set NJW_NO_BROWSER=1 to skip opening a browser (headless machines, tests).
"""
from __future__ import annotations

import os
import platform
import shutil
import stat
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PORT = 8000
DESKTOP_NAME = "Launch NJ Wholesale Dashboard"
# Exit 0 only when OUR cockpit answers (a refused connection raises, which exits non-zero).
HEALTH = ("import sys,urllib.request as u; sys.exit(0 if b'nj-wholesale-cockpit' in "
          "u.urlopen('http://127.0.0.1:{port}/api/health',timeout=2).read() else 1)")

UNIX = r'''#!/usr/bin/env bash
# NJ Wholesale Dashboard launcher (generated by scripts/install_desktop_shortcut.py).
# Starts the local cockpit if it isn't running, waits for it, and opens http://127.0.0.1:{port}
REPO={repo}
cd "$REPO" || {{ echo "Can't open the project folder: $REPO"; exit 1; }}
URL="http://127.0.0.1:{port}"
PY=""
for c in "$REPO/.venv/bin/python" "$REPO/venv/bin/python" python3 python; do
  if command -v "$c" >/dev/null 2>&1; then PY="$c"; break; fi
done
[ -n "$PY" ] || {{ echo "Python 3 is not installed. Install it from python.org, then run: pip install -e ."; exit 1; }}
healthy() {{ "$PY" -c "{health}" >/dev/null 2>&1; }}
if ! healthy; then
  mkdir -p logs
  echo "Starting the dashboard (log: $REPO/logs/server.log)..."
  nohup "$PY" manage.py server --port {port} >> logs/server.log 2>&1 &
  for _ in $(seq 1 60); do
    healthy && break
    sleep 0.5
  done
fi
if ! healthy; then
  echo "The dashboard didn't start. Last lines of logs/server.log:"
  tail -n 20 logs/server.log 2>/dev/null
  [ -t 0 ] && read -r -p "Press Enter to close" _
  exit 1
fi
echo "Dashboard running at $URL"
if [ -z "$NJW_NO_BROWSER" ]; then
  if command -v open >/dev/null 2>&1; then open "$URL"
  elif command -v xdg-open >/dev/null 2>&1; then xdg-open "$URL" >/dev/null 2>&1 &
  else echo "Open $URL in your browser."
  fi
fi
'''

WINDOWS = r'''@echo off
rem NJ Wholesale Dashboard launcher (generated by scripts\install_desktop_shortcut.py).
rem Starts the local cockpit if it isn't running, waits for it, and opens http://127.0.0.1:{port}
setlocal
cd /d {repo}
set "URL=http://127.0.0.1:{port}"
set "PY=python"
if exist ".venv\Scripts\python.exe" set "PY=.venv\Scripts\python.exe"
if exist "venv\Scripts\python.exe" set "PY=venv\Scripts\python.exe"
"%PY%" -c "{health}" >nul 2>&1 && goto ready
if not exist logs mkdir logs
echo Starting the dashboard (log: logs\server.log)...
start "NJ Wholesale Cockpit" /min cmd /c ""%PY%" manage.py server --port {port} >> logs\server.log 2>&1"
for /L %%i in (1,1,60) do (
  "%PY%" -c "{health}" >nul 2>&1 && goto ready
  timeout /t 1 /nobreak >nul
)
echo The dashboard didn't start. See logs\server.log
pause
exit /b 1
:ready
echo Dashboard running at %URL%
if not defined NJW_NO_BROWSER start "" "%URL%"
'''

DESKTOP_ENTRY = """[Desktop Entry]
Type=Application
Name={name}
Comment=Start and open the NJ wholesale command center
Exec=bash {script}
Terminal=false
Icon=applications-internet
"""


def _health() -> str:
    return HEALTH.format(port=PORT)


def unix_script(repo: str | None = None) -> str:
    """repo=None: path-independent (the script's own folder). Otherwise the absolute repository path."""
    return UNIX.format(repo='"$(cd "$(dirname "$0")" && pwd)"' if repo is None else _sh_quote(repo),
                       port=PORT, health=_health())


def windows_script(repo: str | None = None) -> str:
    return WINDOWS.format(repo='"%~dp0"' if repo is None else f'"{repo}"', port=PORT, health=_health())


def _sh_quote(path: str) -> str:
    return "'" + path.replace("'", "'\\''") + "'"


def _write(path: Path, text: str, executable: bool, crlf: bool = False) -> Path:
    data = text.replace("\n", "\r\n") if crlf else text
    path.write_bytes(data.encode("utf-8"))
    if executable:
        path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    return path


def install(desktop: Path | None = None, system: str | None = None, repo: Path = ROOT) -> dict[str, list[str]]:
    """Write the repository launchers and the Desktop copy for this OS. Returns what was written."""
    system = system or platform.system()
    written = [
        _write(repo / "Launch_Dashboard.command", unix_script(), executable=True),
        _write(repo / "launch_dashboard.sh", unix_script(), executable=True),
        _write(repo / "Launch_Dashboard.bat", windows_script(), executable=False, crlf=True),
    ]
    desktop = desktop if desktop is not None else Path.home() / "Desktop"
    copies: list[Path] = []
    if desktop.is_dir():
        if system == "Darwin":
            copies.append(_write(desktop / f"{DESKTOP_NAME}.command", unix_script(str(repo)), executable=True))
        elif system == "Windows":
            copies.append(_write(desktop / f"{DESKTOP_NAME}.bat", windows_script(str(repo)), executable=False,
                                 crlf=True))
        else:
            script = _write(desktop / f"{DESKTOP_NAME}.sh", unix_script(str(repo)), executable=True)
            entry = _write(desktop / "nj-wholesale-dashboard.desktop",
                           DESKTOP_ENTRY.format(name=DESKTOP_NAME, script='"' + str(script).replace('"', '\\"') + '"'),
                           executable=True)
            copies += [script, entry]
    return {"repo": [str(p) for p in written], "desktop": [str(p) for p in copies],
            "desktop_dir": str(desktop) if desktop.is_dir() else ""}


def main(argv: list[str] | None = None) -> int:
    import argparse
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--desktop", help="folder to put the shortcut in (default ~/Desktop)")
    args = ap.parse_args(argv)
    out = install(Path(args.desktop).expanduser() if args.desktop else None)
    for p in out["repo"]:
        print(f"wrote {os.path.relpath(p, ROOT)}")
    if out["desktop"]:
        for p in out["desktop"]:
            print(f"desktop shortcut: {p}")
    else:
        print("No Desktop folder found: double-click Launch_Dashboard.command (macOS), launch_dashboard.sh (Linux) "
              "or Launch_Dashboard.bat (Windows) in the project folder instead.")
    if shutil.which("python3") is None and sys.platform != "win32":
        print("note: python3 is not on PATH; the launcher will use the project's .venv if it exists.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
